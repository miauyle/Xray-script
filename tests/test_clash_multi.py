class MultiGeneratorTests(unittest.TestCase):
    def test_peers_and_old_yaml_is_unchanged(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            single = root / "clash.yaml"
            multi_yaml = root / "multi_clash.yaml"
            provider = root / "proxies.yaml"
            config = root / "multi-server.json"
            single.write_text(SINGLE)
            multi.edit_config(config, "add", "KR", "http://203.0.113.10/sub/" + "X" * 43 + "/proxies.yaml")
            multi.edit_config(config, "enable")
            data = multi.load_config(config)
            local, aggregate = multi.render_files(SINGLE, data["peers"])
            multi.atomic_text(provider, local)
            multi.atomic_text(multi_yaml, aggregate)
            self.assertEqual(single.read_text(), SINGLE)
            self.assertNotIn("proxy-providers:", local)
            self.assertNotIn("rules:", local)
            self.assertEqual(local.count("  - name:"), 2)
            self.assertIn("proxy-providers:", aggregate)
            self.assertIn("additional-prefix: \"KR-\"", aggregate)
            self.assertIn("Failover", aggregate)
            self.assertIn("consistent-hashing", aggregate)
            self.assertIn("GEOIP,CN,DIRECT,no-resolve", aggregate)
            self.assertEqual(aggregate.count("proxy-groups:"), 1)
            self.assertEqual(aggregate.count("rules:"), 1)
            self.assertEqual(provider.stat().st_mode & 0o777, 0o600)
            self.assertEqual(config.stat().st_mode & 0o777, 0o600)

    def test_single_peerless_degradation(self):
        local, aggregated = multi.render_files(SINGLE, [])
        self.assertIn("Fallback-XHTTP-Reality", local)
        self.assertNotIn("proxy-providers:", aggregated)
        self.assertIn("name: \"Auto\"", aggregated)

    def test_rejects_duplicate_bad_provider_and_malformed_yaml(self):
        url = "http://203.0.113.10/sub/" + "z" * 43 + "/proxies.yaml"
        with tempfile.TemporaryDirectory() as td:
            conf = Path(td) / "multi-server.json"
            multi.edit_config(conf, "add", "KR", url)
            with self.assertRaises(ValueError):
                multi.edit_config(conf, "add", "JP", url)
            with self.assertRaises(ValueError):
                multi.edit_config(conf, "add", "evil\nname", url)
            with self.assertRaises(ValueError):
                multi.edit_config(conf, "add", "SAFE", "http://invalid/sub/token/multi_clash.yaml")
            self.assertEqual(len(multi.load_config(conf)["peers"]), 1)
            with self.assertRaises(ValueError):
                multi.render_files("proxies: []\n", [])
            multi.edit_config(conf, "remove", "KR")
            self.assertEqual(multi.load_config(conf)["peers"], [])


class HttpRouteTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        for filename, body in (
            ("clash.yaml", "old-single"),
            ("multi_clash.yaml", "new-multi"),
            ("proxies.yaml", "local-provider"),
        ):
            (self.root / filename).write_text(body)
        for filename, value in (
            ("single.token", "single-secret"),
            ("multi.token", "multi-secret"),
            ("provider.token", "provider-secret"),
            ("provider.token.next", "next-provider-secret"),
        ):
            (self.root / filename).write_text(value)
        self.server = ThreadingHTTPServer(("127.0.0.1", 0), http.Handler)
        self.server.token_file = self.root / "single.token"
        self.server.yaml_file = self.root / "clash.yaml"
        self.server.multi_token_file = self.root / "multi.token"
        self.server.multi_yaml_file = self.root / "multi_clash.yaml"
        self.server.provider_token_file = self.root / "provider.token"
        self.server.provider_next_token_file = self.root / "provider.token.next"
        self.server.provider_yaml_file = self.root / "proxies.yaml"
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()

    def tearDown(self):
        self.server.shutdown()
        self.thread.join(timeout=5)
        self.server.server_close()
        self.temp.cleanup()

    def request(self, uri):
        url = "http://127.0.0.1:" + str(self.server.server_port) + uri
        try:
            with urllib.request.urlopen(url, timeout=3) as resp:
                return resp.status, resp.read().decode(), resp.headers
        except urllib.error.HTTPError as exc:
            return exc.code, "", exc.headers

    def test_scoped_routes_and_token_rotation(self):
        for token, filename, expected in (
            ("single-secret", "clash.yaml", "old-single"),
            ("multi-secret", "multi_clash.yaml", "new-multi"),
            ("provider-secret", "proxies.yaml", "local-provider"),
            ("next-provider-secret", "proxies.yaml", "local-provider"),
        ):
            code, value, headers = self.request("/sub/" + token + "/" + filename)
            self.assertEqual((code, value), (200, expected))
            self.assertEqual(headers["Cache-Control"], "no-store")
        for path in (
            "/sub/single-secret/multi_clash.yaml",
            "/sub/multi-secret/clash.yaml",
            "/sub/provider-secret/multi_clash.yaml",
            "/sub/missing/proxies.yaml",
            "/sub/../single-secret/clash.yaml",
        ):
            self.assertEqual(self.request(path)[0], 404, path)

        (self.root / "provider.token").write_text("rotated-provider")
        (self.root / "provider.token.next").unlink()
        self.assertEqual(self.request("/sub/provider-secret/proxies.yaml")[0], 404)
        self.assertEqual(self.request("/sub/next-provider-secret/proxies.yaml")[0], 404)
        self.assertEqual(self.request("/sub/rotated-provider/proxies.yaml")[0], 200)
        (self.root / "multi.token").unlink()
        self.assertEqual(self.request("/sub/multi-secret/multi_clash.yaml")[0], 404)
        self.assertEqual(self.request("/sub/single-secret/clash.yaml")[0], 200)


