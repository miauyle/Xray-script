CLASH = (ROOT / "core" / "clash.sh").read_text(encoding="utf-8")


def shell_function(name):
    pattern = r"(?ms)^function " + re.escape(name) + r"\(\) \{.*?^\}"
    match = re.search(pattern, CLASH)
    assert match, "Missing Clash function: " + name
    return match.group(0)


FUNCTIONS = "\n".join(shell_function(n) for n in (
    "yaml_quote",
    "inbound_value",
    "reality_server_name",
    "reality_short_id",
    "xray_reality_needs_mlkem",
    "append_vless_reality_node",
))


def generate_nodes(server_version, script_version="v26.3.27"):
    # Use the actual Fallback JSON template and exact Bash generator functions.
    # Intentionally stale script_version: installed xray must win.
    config = {
        "xray": {"publicKey": "PUBKEY-TEST", "port": 443,
                 "version": script_version},
        "nginx": {"domain": "www.cloudflare.com"},
    }
    template = json.loads((ROOT / "config/xray/Fallback.json").read_text())
    for inbound in template.get("inbounds", []):
        for client in inbound.get("settings", {}).get("clients", []):
            if "id" in client:
                client["id"] = "123e4567-e89b-42d3-a456-426614174000"
    code = "\n".join([
        "SCRIPT_CONFIG=" + shlex.quote(json.dumps(config)),
        "XRAY_CONFIG=" + shlex.quote(json.dumps(template)),
        "NODE_NAMES=()",
        "PROXY_BUFFER=''",
        "XRAY_MLKEM_REQUIRED=0",
        "xray() { echo 'Xray " + server_version + " (test binary)'; }",
        "warn() { echo \"$*\" >&2; }",
        FUNCTIONS,
        "if xray_reality_needs_mlkem; then XRAY_MLKEM_REQUIRED=1; fi",
        "append_vless_reality_node Fallback-Vision-Reality 1 1 198.51.100.10",
        "append_vless_reality_node Fallback-XHTTP-Reality 2 1 198.51.100.10",
        "printf '%b' \"$PROXY_BUFFER\"",
    ])
    proc = subprocess.run(["bash", "-c", code], text=True,
                          capture_output=True, cwd=ROOT, timeout=15)
    if proc.returncode:
        raise AssertionError(proc.stderr)
    return proc.stdout


def make_single(nodes):
    return (
        "# Generated by Xray-script for Clash Verge Rev / Mihomo.\n"
        "mixed-port: 7890\nmode: rule\n"
        + clash_multi.PROXY_MARKER + nodes
        + clash_multi.GROUP_MARKER
        + "  - name: Proxy\n    type: select\n    proxies:\n      - Auto\n"
        + clash_multi.RULE_MARKER + "  - MATCH,Proxy\n"
    )


class RealityMlkemTests(unittest.TestCase):
    def test_gate_by_installed_binary_not_cached_version(self):
        for server, count in [
            ("26.3.27", 0), ("26.7.11", 0), ("26.9.7", 0),
            ("26.9.8", 2), ("26.9.9", 2), ("26.10.21", 2),
            ("27.0.0", 2), ("not-a-version", 0),
        ]:
            with self.subTest(xray=server):
                nodes = generate_nodes(server)
                self.assertEqual(nodes.count("support-x25519mlkem768: true"), count)
                self.assertEqual(nodes.count("client-fingerprint: chrome"), 2)
                self.assertEqual(nodes.count("    reality-opts:"), 2)
                self.assertEqual(nodes.count("      public-key:"), 2)
                self.assertNotIn("support-x25519mlkem768: false", nodes)
                self.assertNotIn("support-x25519mlkem768: 'true'", nodes)

        # Correctly disable the option for an old actual server despite a
        # recently recorded version in script config.
        self.assertNotIn("support-x25519mlkem768",
                         generate_nodes("26.3.27", script_version="v26.10.21"))

    def test_every_publication_retains_the_flag_without_provider_override(self):
        for server, count in [("26.10.21", 2), ("26.3.27", 0)]:
            with self.subTest(server=server):
                nodes = generate_nodes(server)
                single = make_single(nodes)
                peers = [{"name": "Tokyo", "url":
                          "https://provider.example.com/sub/"
                          + "Z" * 43 + "/proxies.yaml"}]
                provider, aggregate = clash_multi.render_files(single, peers)
                for document in (single, provider, aggregate):
                    self.assertEqual(document.count("support-x25519mlkem768: true"), count)
                    self.assertEqual(document.count("client-fingerprint: chrome"), 2)
                self.assertIn("proxy-providers:", aggregate)
                self.assertIn("additional-prefix: \"Tokyo-\"", aggregate)
                self.assertNotIn("override-expr:", aggregate)
                self.assertNotIn("support-x25519mlkem768", aggregate.split("proxy-providers:", 1)[1].split("proxy-groups:", 1)[0])
                self.assertNotIn("proxy-providers:", provider)
                parsed = clash_shadowrocket.parse_provider(provider)
                self.assertEqual(len(parsed), 2)
                if count:
                    self.assertTrue(all(node["reality-opts"]["support-x25519mlkem768"] == "true"
                                        for node in parsed))
                else:
                    self.assertTrue(all("support-x25519mlkem768" not in node["reality-opts"]
                                        for node in parsed))


